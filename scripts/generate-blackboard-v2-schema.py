#!/usr/bin/env python3
"""Assemble the frozen Blackboard v2 schema from concept source fragments."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "internal/blackboardv2contract/schema-sources"
OUTPUT = ROOT / "internal/blackboardv2contract/contractdata/schemas/blackboard-v2.schema.json"
GENERATED_COMMENT = "Code generated by scripts/generate-blackboard-v2-schema.py; DO NOT EDIT."


def load_json(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SystemExit(f"{path}: invalid JSON: {exc}") from exc


def build_schema():
    index_path = SOURCE_DIR / "index.json"
    index = load_json(index_path)
    fragments = index.get("fragments")
    if not isinstance(fragments, list) or not fragments or not all(isinstance(name, str) for name in fragments):
        raise SystemExit(f"{index_path}: fragments must be a non-empty string array")
    if len(fragments) != len(set(fragments)):
        raise SystemExit(f"{index_path}: fragments contains a duplicate")

    source_files = {path.name for path in SOURCE_DIR.glob("*.json") if path.name != "index.json"}
    listed_files = set(fragments)
    if source_files != listed_files:
        missing = sorted(listed_files - source_files)
        unlisted = sorted(source_files - listed_files)
        raise SystemExit(f"{index_path}: fragment list mismatch; missing={missing} unlisted={unlisted}")

    definitions = {}
    for fragment in fragments:
        path = SOURCE_DIR / fragment
        data = load_json(path)
        if not isinstance(data, dict) or not data:
            raise SystemExit(f"{path}: expected a non-empty object of schema definitions")
        for name, definition in data.items():
            if name in definitions:
                raise SystemExit(f"{path}: duplicate schema definition {name!r}")
            if not isinstance(definition, dict):
                raise SystemExit(f"{path}: schema definition {name!r} must be an object")
            definitions[name] = definition

    return {
        "$comment": GENERATED_COMMENT,
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://cyberpenda.local/schemas/blackboard-v2.schema.json",
        "$defs": definitions,
    }


def render_schema():
    return json.dumps(build_schema(), indent=2, ensure_ascii=False) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the frozen schema is not current")
    args = parser.parse_args()

    rendered = render_schema()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(f"{OUTPUT}: stale; run scripts/generate-blackboard-v2-schema.py", file=sys.stderr)
            return 1
        return 0

    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
